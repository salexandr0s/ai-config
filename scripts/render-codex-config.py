#!/usr/bin/env python3
"""Merge the shared Codex config and private overlay, then replace atomically."""

from copy import deepcopy
from datetime import date, datetime, time
import json
import math
import os
from pathlib import Path
import sys
import tempfile
import tomllib


def merge(base, override):
    result = deepcopy(base)
    for key, value in override.items():
        if isinstance(value, dict) and isinstance(result.get(key), dict):
            result[key] = merge(result[key], value)
        else:
            result[key] = deepcopy(value)
    return result


def quoted(value):
    # TOML forbids literal DEL; JSON leaves it raw with ensure_ascii=False.
    return json.dumps(value, ensure_ascii=False).replace("\x7f", "\\u007f")


def toml_value(value):
    if isinstance(value, str):
        return quoted(value)
    if isinstance(value, bool):
        return str(value).lower()
    if isinstance(value, (int, float)):
        return repr(value)
    if isinstance(value, (datetime, date, time)):
        return value.isoformat()
    if isinstance(value, list):
        return "[" + ", ".join(toml_value(item) for item in value) + "]"
    if isinstance(value, dict):
        return "{ " + ", ".join(
            f"{quoted(key)} = {toml_value(item)}" for key, item in value.items()
        ) + " }"
    raise ValueError(f"Unsupported TOML value type: {type(value).__name__}")


def dump_toml(config):
    lines = []

    def table(value, path, header=None):
        if header:
            lines.extend(["", header])
        children = []
        for key, item in value.items():
            child_path = (*path, key)
            is_tables = isinstance(item, list) and item and all(
                isinstance(entry, dict) for entry in item
            )
            if isinstance(item, dict) or is_tables:
                children.append((child_path, item, is_tables))
            else:
                lines.append(f"{quoted(key)} = {toml_value(item)}")
        for child_path, item, is_tables in children:
            name = ".".join(quoted(part) for part in child_path)
            if is_tables:
                for entry in item:
                    table(entry, child_path, f"[[{name}]]")
            else:
                table(item, child_path, f"[{name}]")

    table(config, ())
    return "\n".join(lines).lstrip() + "\n"


def load_toml(path, optional=False):
    if optional and not path.exists():
        return {}
    with path.open("rb") as source:
        return tomllib.load(source)


def comparable(value):
    """NaN is valid TOML but does not compare equal to itself."""
    if isinstance(value, float) and math.isnan(value):
        return ("TOML float", "nan")
    if isinstance(value, dict):
        return {key: comparable(item) for key, item in value.items()}
    if isinstance(value, list):
        return [comparable(item) for item in value]
    return value


def render(repo, home, config_home):
    base_path = repo / "codex/config.base.toml"
    local_path = config_home / "codex/config.local.toml"
    target = home / ".codex/config.toml"
    # Shared keys replace prior values; unowned keys, including native plugin
    # state, survive upgrades. The explicit private overlay has final precedence.
    previous = load_toml(target, optional=True)
    config = merge(previous, load_toml(base_path))
    config = merge(config, {"profiles": {
        name: {
            "model_verbosity": verbosity,
            "model_instructions_file": str(home / ".codex/instructions" / f"{name}.md"),
        }
        for name, verbosity in (("concise", "low"), ("technical", "high"), ("review", "medium"))
    }})
    config = merge(config, load_toml(local_path, optional=True))
    rendered = "# Generated by ai-config; edit the shared base or private local overlay.\n"
    rendered += dump_toml(config)
    if comparable(tomllib.loads(rendered)) != comparable(config):
        raise ValueError("Rendered TOML did not preserve the merged configuration")

    target.parent.mkdir(parents=True, exist_ok=True)
    fd, temporary_name = tempfile.mkstemp(prefix=".config-", suffix=".toml", dir=target.parent)
    temporary = Path(temporary_name)
    try:
        with os.fdopen(fd, "w", encoding="utf-8") as output:
            os.fchmod(output.fileno(), 0o600)
            output.write(rendered)
            output.flush()
            os.fsync(output.fileno())
        os.replace(temporary, target)
    finally:
        temporary.unlink(missing_ok=True)
    return target


def main():
    repo = Path(__file__).resolve().parents[1]
    home = Path.home()
    config_home = Path(os.environ.get("XDG_CONFIG_HOME", home / ".config"))
    try:
        target = render(repo, home, config_home)
    except (OSError, ValueError) as error:
        print(f"Codex config was not replaced: {error}", file=sys.stderr)
        return 1
    print(f"Rendered {target}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
